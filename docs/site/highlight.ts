// Highlights snippets.txt into snippets.gen.ts at build time, so the site ships HTML and no highlighter.
// The grammar is the VS Code extension's; the theme below colors each of its scopes.
import { createHighlighter, type ThemeRegistration } from "shiki";
import { join } from "node:path";

const here = import.meta.dir;
const grammar = await Bun.file(join(here, "../../editors/vscode/syntaxes/xzor.tmLanguage.json")).json();

const c = {
  bg: "#0f1222",
  fg: "#d6deeb",
  muted: "#6b7394",
  transition: "#ff9e64",
  directive: "#ff9e64",
  keyword: "#c792ea",
  component: "#2ac3de",
  tag: "#7aa2f7",
  attribute: "#bb9af7",
  event: "#f7768e",
  string: "#a5d6a7",
  number: "#f78c6c",
  slot: "#e0af68",
  cascade: "#9ece6a",
  type: "#4fd6be",
  fn: "#82aaff",
  variable: "#d6deeb",
};

const theme: ThemeRegistration = {
  name: "xzor-night",
  type: "dark",
  colors: { "editor.background": c.bg, "editor.foreground": c.fg },
  tokenColors: [
    { scope: ["comment", "punctuation.definition.comment"], settings: { foreground: c.muted, fontStyle: "italic" } },
    // xzor's own syntax
    { scope: ["keyword.control.transition.xzor", "punctuation.section.embedded.begin.xzor", "punctuation.section.embedded.end.xzor"], settings: { foreground: c.transition, fontStyle: "bold" } },
    { scope: ["keyword.control.directive.xzor", "keyword.other.fixed.xzor", "keyword.control.as.xzor"], settings: { foreground: c.directive } },
    { scope: "keyword.control.xzor", settings: { foreground: c.keyword } },
    { scope: "support.class.component.xzor", settings: { foreground: c.component, fontStyle: "bold" } },
    { scope: "entity.other.attribute-name.event.xzor", settings: { foreground: c.event } },
    { scope: ["entity.name.function.slot.xzor", "punctuation.separator.slot.xzor"], settings: { foreground: c.slot } },
    { scope: ["variable.other.constant.cascade.xzor", "variable.other.constant.route.xzor", "punctuation.separator.cascade.xzor"], settings: { foreground: c.cascade } },
    { scope: ["entity.name.type.parameter.xzor", "variable.parameter.xzor"], settings: { foreground: c.type } },
    // HTML inside templates
    { scope: ["entity.name.tag", "punctuation.definition.tag"], settings: { foreground: c.tag } },
    { scope: "entity.other.attribute-name", settings: { foreground: c.attribute } },
    { scope: ["string", "punctuation.definition.string"], settings: { foreground: c.string } },
    { scope: "constant.character", settings: { foreground: c.number } },
    // TypeScript (in @code, expressions and .ts files) and the shell
    { scope: ["keyword", "storage", "storage.type", "keyword.operator.new", "keyword.operator.expression"], settings: { foreground: c.keyword } },
    { scope: ["entity.name.type", "support.type", "entity.name.class", "entity.other.inherited-class"], settings: { foreground: c.type } },
    { scope: ["entity.name.function", "support.function", "meta.decorator entity.name.function"], settings: { foreground: c.fn } },
    { scope: ["constant.numeric", "constant.language"], settings: { foreground: c.number } },
    { scope: ["variable.other.property", "variable.other.object.property", "meta.object-literal.key"], settings: { foreground: c.fg } },
    { scope: ["punctuation.decorator", "meta.decorator"], settings: { foreground: c.transition } },
    { scope: ["support.type.property-name.json"], settings: { foreground: c.attribute } },
  ],
};

const highlighter = await createHighlighter({
  themes: [theme],
  langs: [{ ...grammar, name: "xzor", embeddedLangs: ["typescript"] }, "typescript", "json", "jsonc", "html", "shellscript", "powershell"],
});

// `--- name | file | lang` opens a snippet; everything up to the next one is its code.
const text = await Bun.file(join(here, "snippets.txt")).text();
const entries: string[] = [];
for (const block of text.replace(/\r\n/g, "\n").split(/^--- /m).slice(1)) {
  const newline = block.indexOf("\n");
  const [name, file, lang] = block.slice(0, newline).split("|").map((s) => s.trim());
  const code = block.slice(newline + 1).replace(/\n+$/, "");
  const html = highlighter.codeToHtml(code, { lang: lang!, theme: "xzor-night" });
  entries.push(`  ${JSON.stringify(name)}: { file: ${JSON.stringify(file)}, html: ${JSON.stringify(html)} },`);
}

await Bun.write(
  join(here, "snippets.gen.ts"),
  `// Generated by highlight.ts from snippets.txt. Do not edit.\nexport const snippets = {\n${entries.join("\n")}\n} as const;\n\nexport type SnippetName = keyof typeof snippets;\n`,
);
console.log(`highlighted ${entries.length} snippets`);
