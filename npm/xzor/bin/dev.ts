// `xzor dev`, run by the launcher under Bun: `xzor build --watch --hot`, a static server with the SPA fallback,
// and live reload: after each build open pages patch the components the edit changed, stay as they are when the
// edit changed no generated code, or reload when nothing could be patched. A server app's generated server runs behind it
// (`XZOR_DEV=1`, on a port of its own) and answers what no file does; any build that can't hot-patch restarts it.
// Tests import `prepareModule`; the server only runs when this file is the entry.
// argv: <xzor binary> [build options...]
import { join, resolve, sep } from "node:path";

const transpiler = new Bun.Transpiler({ loader: "ts" });
const IMPORT_CLAUSE = /^import\s+([^"']+?)\s+from\s*["'][^"']+["']/gm;

/** Local names bound by the value imports of a transpiled module (the transpiler drops the type-only ones).
 *  Mirrors `valueImportLocals` in src/bundle.ts; tests/dev-hot.test.ts keeps them in step. */
function importLocals(js: string): string[] {
  const locals: string[] = [];
  for (const m of js.matchAll(IMPORT_CLAUSE)) {
    const clause = m[1]!;
    const named = /\{([^}]*)\}/.exec(clause);
    for (const part of clause.replace(/\{[^}]*\}/, "").split(",")) {
      const local = part.trim().replace(/^\*\s*as\s+/, "");
      if (local) locals.push(local);
    }
    for (const spec of named?.[1]!.split(",") ?? []) {
      const local = spec.trim().split(/\s+as\s+/).pop()!;
      if (local) locals.push(local);
    }
  }
  return locals;
}

/** A generated component's module as the hot client evaluates it: no imports, no exports, returning its class. */
export function prepareModule(ts: string): { code: string; imports: string[] } {
  const js = transpiler.transformSync(ts);
  const cls = /^export default class (\w+)/m.exec(js)?.[1];
  const body = js
    .replace(/^import\s.*$/gm, "")
    .replace(/^export default (class)/m, "$1")
    .replace(/^export\s+/gm, "");
  return { code: cls ? `${body}\nreturn ${cls};` : body, imports: importLocals(js) };
}

/** Served at `/sw.js` in dev: replaces a production worker, which would serve stale files, and reloads its pages uncontrolled. */
export const RETIRE_WORKER = `self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => e.waitUntil((async () => {
  for (const k of await caches.keys()) if (k.startsWith("xzor-")) await caches.delete(k);
  await self.registration.unregister();
  for (const c of await self.clients.matchAll({ type: "window" })) c.navigate(c.url);
})()));
`;

/** Whether `/sw.js` is retired: there is no `<root>/sw.js`, or it is one xzor generated; a user's own worker is served as is. */
export const retiresWorker = (text: string | undefined): boolean => text === undefined || text.startsWith("// Generated by xzor. Do not edit.");

/** The generated server entry (`.xzor/<app file>`, relative to `root`) when the project is a server app. */
export async function findServerEntry(root: string): Promise<string | undefined> {
  const gen = join(root, ".xzor");
  for await (const f of new Bun.Glob("**/*.ts").scan({ cwd: gen })) {
    if (/\.(xzor|provider)\.ts$/.test(f)) continue;
    if ((await Bun.file(join(gen, f)).text()).includes("= Bun.serve(")) return join(".xzor", f);
  }
}

if (import.meta.main) {
  const [exe, ...args] = process.argv.slice(2);
  const root = process.cwd();
  const watch = Bun.spawn([exe!, "build", "--watch", "--hot", ...args], { stdio: ["inherit", "pipe", "inherit"] });

  // Pages listening for rebuilds (Server-Sent Events).
  const clients = new Set<ReadableStreamDefaultController<string>>();
  const send = (data: string) => {
    for (const c of clients) c.enqueue(`data: ${data}\n\n`);
  };

  let pending: ReturnType<typeof setTimeout> | undefined;
  // Ids to patch at the next flush, the ones the running build printed, whether it printed the bare no-change
  // marker, and whether anything was unpatchable.
  const queued = new Set<string>();
  let printed: string[] = [];
  let noChange = false;
  let unpatchable = false;

  // The generated server of a server app, and its URL once it prints it.
  let child: { proc: ReturnType<typeof Bun.spawn>; url: Promise<string> } | undefined;
  const startServer = (file: string) => {
    const url = Promise.withResolvers<string>();
    const proc = Bun.spawn(["bun", file], { cwd: root, env: { ...process.env, PORT: "0", XZOR_DEV: "1" }, stdout: "pipe", stderr: "inherit" });
    void (async () => {
      const decoder = new TextDecoder();
      let seen = "";
      for await (const chunk of proc.stdout) {
        process.stdout.write(chunk);
        if (seen !== "") continue;
        const m = /https?:\/\/\S+/.exec(decoder.decode(chunk, { stream: true }));
        if (m) url.resolve((seen = m[0]));
      }
      if (seen === "") url.reject(new Error("the server exited before it listened"));
    })();
    url.promise.catch(() => {});
    child = { proc, url: url.promise };
  };
  // A build that passed and could not hot-patch (a `.ts` changed) starts or restarts the server.
  let passed = args.includes("--no-check");
  let hotSeen = false;
  const rebuilt = async () => {
    const ok = passed;
    const patchable = hotSeen;
    passed = args.includes("--no-check");
    hotSeen = false;
    if (!ok || (child && patchable)) return;
    const file = await findServerEntry(root);
    if (!file) return;
    if (child) {
      const old = child.proc;
      old.kill();
      await old.exited;
    }
    startServer(file);
  };

  const flush = async () => {
    const ids = [...queued];
    queued.clear();
    const reload = unpatchable;
    unpatchable = false;
    if (!reload && ids.length === 0) return;
    if (reload || ids.some((id) => !resolve(root, id).startsWith(root + sep))) return send("reload");
    try {
      const hot = await Promise.all(ids.map(async (id) => ({ id, ...prepareModule(await Bun.file(resolve(root, id)).text()) })));
      send(JSON.stringify({ hot }));
    } catch {
      send("reload");
    }
  };
  // A written bundle (`.../dist/x.js`) ends a successful build; the `xzor: hot` lines before it name what it patches.
  const built = () => {
    if (printed.length) for (const id of printed) queued.add(id);
    else if (!noChange) unpatchable = true;
    printed = [];
    noChange = false;
    clearTimeout(pending);
    pending = setTimeout(flush, 50);
  };

  // The build output passes through.
  void (async () => {
    const decoder = new TextDecoder();
    let rest = "";
    for await (const chunk of watch.stdout) {
      process.stdout.write(chunk);
      const lines = (rest + decoder.decode(chunk, { stream: true })).split("\n");
      rest = lines.pop()!;
      for (const line of lines) {
        const hot = /^xzor: hot (.+?)\s*$/.exec(line);
        if (hot) {
          printed.push(hot[1]!);
          hotSeen = true;
        } else if (/^xzor: hot\s*$/.test(line)) noChange = hotSeen = true;
        else if (/^xzor: type check passed\s*$/.test(line)) passed = true;
        else if (/^xzor: watching /.test(line)) await rebuilt();
        else if (/[\\/]dist[\\/][^\\/]+\.js\s*$/.test(line)) built();
      }
    }
  })();

  const build = await Bun.build({ entrypoints: [join(import.meta.dir, "hot-client.ts")], format: "iife", target: "browser" });
  const hotClient = await build.outputs[0]!.text();
  // A classic script right after `<head>`: the registry must exist before the app's module scripts run.
  const client = `<script src="/__xzor/hot.js"></script>`;
  const inject = (text: string) =>
    /<head[^>]*>/i.test(text) ? text.replace(/<head[^>]*>/i, (head) => head + client) : text.replace(/<script/i, `${client}<script`);
  // Never cached, so a reload always gets the latest build.
  const headers = { "Cache-Control": "no-store" };
  // A server app's `index.html` has no script or stylesheet of its own: the bundle's are added, as the production build does.
  const withMain = async (text: string) => {
    if (!child) return text;
    if (!/main\.css/.test(text) && (await Bun.file(resolve(root, "dist", "main.css")).exists())) {
      text = text.replace(/<\/head\s*>/i, `<link rel="stylesheet" href="dist/main.css">\n$&`);
    }
    return /main\.js/.test(text) ? text : text.replace(/<\/body\s*>/i, `<script type="module" src="dist/main.js"></script>\n$&`);
  };
  const html = async (file: string) =>
    new Response(inject(await withMain(await Bun.file(file).text())), { headers: { ...headers, "Content-Type": "text/html;charset=utf-8" } });

  // What no file answers goes to the app's server; a page path it doesn't know is a client route.
  const proxy = async (req: Request): Promise<Response> => {
    const url = new URL(req.url);
    let res: Response;
    try {
      const headers = new Headers(req.headers);
      headers.delete("host");
      const body = req.method === "GET" || req.method === "HEAD" ? undefined : await req.arrayBuffer();
      // The origin plus the path: a `//host` path must not resolve as protocol-relative.
      const target = new URL(await child!.url);
      target.pathname = url.pathname;
      target.search = url.search;
      res = await globalThis.fetch(target, { method: req.method, headers, body, redirect: "manual" });
    } catch {
      return new Response("xzor dev: the server is not running", { status: 502, headers });
    }
    const index = resolve(root, "index.html");
    if (res.status === 404 && req.method === "GET" && req.headers.get("accept")?.includes("text/html") && (await Bun.file(index).exists())) return html(index);
    return res;
  };

  const handle = async (req: Request) => {
    const { pathname } = new URL(req.url);
    if (pathname === "/__xzor/hot.js") return new Response(hotClient, { headers: { ...headers, "Content-Type": "text/javascript;charset=utf-8" } });
    if (pathname === "/sw.js") {
      const own = Bun.file(resolve(root, "sw.js"));
      if (retiresWorker((await own.exists()) ? await own.text() : undefined)) {
        return new Response(RETIRE_WORKER, { headers: { ...headers, "Content-Type": "text/javascript;charset=utf-8" } });
      }
    }
    if (pathname === "/__xzor/reload") {
      let self: ReadableStreamDefaultController<string>;
      const stream = new ReadableStream<string>({
        start(c) {
          self = c;
          clients.add(c);
          c.enqueue(": connected\n\n");
        },
        cancel() {
          clients.delete(self);
        },
      });
      return new Response(stream, { headers: { ...headers, "Content-Type": "text/event-stream" } });
    }
    const path = resolve(root, "." + decodeURIComponent(pathname));
    if (path.startsWith(root + sep)) {
      const file = Bun.file(path);
      if (await file.exists()) return path.endsWith(".html") ? html(path) : new Response(file, { headers });
    }
    if (child) return proxy(req);
    // Unknown paths are client routes: the app routes them itself.
    return html(resolve(root, "index.html"));
  };
  // No idle timeout: the reload stream stays open for as long as the page does.
  const listen = (port: number) => Bun.serve({ port, fetch: handle, idleTimeout: 0 });
  let server;
  try {
    server = listen(Number(process.env.PORT) || 3000);
  } catch {
    server = listen(0);
  }
  console.log(`xzor: serving http://localhost:${server.port}/ with live reload (Ctrl+C to stop)`);

  const stop = () => {
    watch.kill();
    child?.proc.kill();
    server.stop(true);
    process.exit(0);
  };
  process.on("SIGINT", stop);
  process.on("SIGTERM", stop);
  await watch.exited;
  child?.proc.kill();
  server.stop(true);
  process.exit(watch.exitCode ?? 0);
}
