import { expect, test } from "bun:test";
import { prepareModule, RETIRE_WORKER, retiresWorker } from "../npm/xzor/bin/dev";
import { valueImportLocals } from "../src/bundle";

const CARD = `// Generated by xzor from Card.xzor. Do not edit.
import { ComponentBase, type RenderTreeBuilder, type RenderFragment } from "@source-crafter/xzor-runtime";

export default class Card extends ComponentBase {
  declare slots: { header?: () => RenderFragment; default?: () => RenderFragment };
  title = "";

  protected override buildRenderTree(__b: RenderTreeBuilder): void {
    __b.openElement("section");
    __b.addContent(this.title);
    __b.closeElement();
  }
}
`;

test("prepareModule drops the imports and exports and returns the class", () => {
  const { code, imports } = prepareModule(CARD);
  expect(code).not.toContain("import");
  expect(code).not.toContain("export");
  expect(code).toContain("class Card extends ComponentBase");
  expect(code.endsWith("\nreturn Card;")).toBe(true);
  expect(imports).toEqual(["ComponentBase"]);
});

test("prepareModule lists default, aliased and namespace import locals", () => {
  const { code, imports } = prepareModule(`import X, { a as b } from "./x";\nimport * as ns from "./ns";\nexport default class C { v = [X, b, ns]; }\n`);
  expect(imports).toEqual(["X", "b", "ns"]);
  expect(code.endsWith("\nreturn C;")).toBe(true);
});

test("dev.ts and bundle.ts agree on a module's import locals", () => {
  const sources = [
    CARD,
    `import X, { a as b } from "./x";\nimport * as ns from "./ns";\nexport default class C { v = [X, b, ns]; }\n`,
    `import type { T } from "./t";\nimport D, * as all from "./d";\nimport {\n  one,\n  two as dos,\n} from "./n";\nexport default class C { v: T = [D, all, one, dos] as never; }\n`,
  ];
  for (const ts of sources) expect(prepareModule(ts).imports).toEqual(valueImportLocals(ts));
});

test("dev retires a missing or generated sw.js and keeps a user's own", () => {
  expect(retiresWorker(undefined)).toBe(true);
  expect(retiresWorker("// Generated by xzor. Do not edit.\nconst CACHE = 1;\n")).toBe(true);
  expect(retiresWorker("// Generated by xzor. Do not edit.\r\nconst CACHE = 1;")).toBe(true);
  expect(retiresWorker("// mine\nself.addEventListener('fetch', () => {});")).toBe(false);
  expect(retiresWorker("")).toBe(false);
});

test("the dev server's /sw.js worker retires production workers", () => {
  expect(RETIRE_WORKER).toContain("registration.unregister()");
  expect(RETIRE_WORKER).toContain("xzor-");
  expect(RETIRE_WORKER).toContain("skipWaiting()");
  expect(RETIRE_WORKER).toContain("navigate(");
});
