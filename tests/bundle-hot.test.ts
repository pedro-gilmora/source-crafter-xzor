import { afterAll, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { hotRegistration } from "../src/bundle";

const root = join(import.meta.dir, "..");
const tmp = mkdtempSync(join(tmpdir(), "xzor-bundle-hot-"));
afterAll(() => rmSync(tmp, { recursive: true, force: true }));

const CARD = `// Generated by xzor from Card.xzor. Do not edit.
import { Component, type RenderTreeBuilder, type RenderFragment } from "@source-crafter/xzor-runtime";

export default class Card extends Component {
  declare slots: { header?: () => RenderFragment; default?: () => RenderFragment };
  title = "";

  protected override buildRenderTree(__b: RenderTreeBuilder): void {
    __b.openElement("section");
    __b.addAttribute("class", "card");
    __b.addContent(this.slots.header?.() ?? Component.fragment((__b) => { __b.openElement("h3"); __b.addContent(this.title); __b.closeElement(); }));
    __b.addContent(this.slots.default?.() ?? null);
    __b.closeElement();
  }
}
`;

test("appends the registration with the value import locals", () => {
  expect(hotRegistration(CARD, ".xzor/Card.xzor.ts")).toBe(
    `${CARD};globalThis.__xzorHot?.register(".xzor/Card.xzor.ts", Card, () => ({ Component }));`,
  );
});

test("default, aliased and namespace imports bind their local names", () => {
  const src = `import X, { a as b } from "./x";\nimport * as ns from "./ns";\nexport default class C { v = [X, b, ns]; }\n`;
  expect(hotRegistration(src, ".xzor/C.xzor.ts")).toBe(`${src};globalThis.__xzorHot?.register(".xzor/C.xzor.ts", C, () => ({ X, b, ns }));`);
});

test("without a default class the source is unchanged", () => {
  const src = `import { a } from "./a";\nexport class C { v = a; }\n`;
  expect(hotRegistration(src, ".xzor/C.xzor.ts")).toBe(src);
});

test("bundles register only with --hot", () => {
  const build = Bun.spawnSync(["cargo", "run", "-q", "--", "build", "examples/counter", "--no-check"], { cwd: root });
  expect(build.exitCode, build.stderr.toString()).toBe(0);
  const bundle = (outdir: string, ...extra: string[]) => {
    const run = Bun.spawnSync(["bun", join(root, "src", "bundle.ts"), join(root, "examples", "counter", ".xzor", "main.ts"), outdir, ...extra], { cwd: root });
    expect(run.exitCode, run.stderr.toString()).toBe(0);
    return readFileSync(join(outdir, "main.js"), "utf8");
  };
  expect(bundle(join(tmp, "hot"), "--hot")).toContain(`__xzorHot?.register(".xzor/Card.xzor.ts"`);
  expect(bundle(join(tmp, "cold"))).not.toContain(`__xzorHot?.register(".xzor/Card.xzor.ts"`);
}, 120_000);
